import Foundation

@main struct PlaybackClockChecks {
    static func main() {
        var checks = 0
        func require(_ value: Bool, _ message: String) { checks += 1; precondition(value, message) }
        var gate = PlaybackClockGate()
        require(!gate.canSchedule(at: 0), "An empty clock must not schedule")
        gate.observe(position: 0, rate: 1, isPlaying: true, at: 1)
        require(!gate.canSchedule(at: 1), "A playing flag alone is not advancing media")
        for time in [1.05, 1.1, 1.2, 1.27] {
            gate.observe(position: 0, rate: 1, isPlaying: true, at: time)
            require(!gate.canSchedule(at: time), "Startup frozen at zero prematurely enabled analysis")
        }
        gate.observe(position: 0.035, rate: 1, isPlaying: true, at: 1.31)
        require(gate.canSchedule(at: 1.31), "Actual forward progress must establish the playback clock")
        let runningRevision = gate.revision
        gate.observe(position: 0.085, rate: 1, isPlaying: true, at: 1.36)
        require(gate.revision == runningRevision, "Normal progression must not restart the metronome")
        require(!gate.canSchedule(at: 1.67), "Stale messages must stop clicks")
        for time in [1.46, 1.56, 1.67] { gate.observe(position: 0.085, rate: 1, isPlaying: true, at: time) }
        require(!gate.canSchedule(at: 1.67), "Repeated frozen timestamps are not a running video")
        gate.observe(position: 0.12, rate: 1, isPlaying: true, at: 1.72)
        require(gate.canSchedule(at: 1.72), "Observed movement can recover a frozen clock")

        gate.requestPause()
        require(!gate.canSchedule(at: 1.72), "Pause intent must stop scheduling immediately")
        gate.observe(position: 0.15, rate: 1, isPlaying: false, at: 1.75)
        gate.observe(position: 0.2, rate: 1, isPlaying: true, at: 1.8)
        gate.observe(position: 0.25, rate: 1, isPlaying: true, at: 1.85)
        require(!gate.canSchedule(at: 1.85), "Buffering must not acknowledge a pending pause")
        gate.observe(position: 0.25, rate: 1, isPlaying: false, isPaused: true, at: 1.9)
        gate.observe(position: 0.25, rate: 1, isPlaying: true, at: 1.95)
        require(!gate.canSchedule(at: 1.95), "Embedded Play must demonstrate motion after pause")
        gate.observe(position: 0.3, rate: 1, isPlaying: true, at: 2)
        require(gate.canSchedule(at: 2), "Embedded Play can resume after pause and observed movement")

        gate.requestSeek(12, at: 3)
        gate.requestPlay()
        gate.observe(position: 1, rate: 1, isPlaying: true, at: 3)
        require(!gate.canSchedule(at: 3), "Play cannot discard an unconfirmed seek")
        gate.observe(position: 12.05, rate: 1, isPlaying: true, at: 3.1)
        require(!gate.canSchedule(at: 3.1), "A seek landing is not proof of ongoing playback")
        gate.observe(position: 12.1, rate: 1, isPlaying: true, at: 3.15)
        require(gate.canSchedule(at: 3.15), "Confirmed seek resumes after forward progress")
        let seekRevision = gate.revision
        gate.observe(position: 3, rate: 1, isPlaying: true, at: 3.2)
        require(gate.revision > seekRevision && !gate.canSchedule(at: 3.2),
                "Embedded seek must invalidate clicks and require new progress")
        gate.observe(position: 3.05, rate: 1, isPlaying: true, at: 3.25)
        require(gate.canSchedule(at: 3.25), "Playback must recover after a completed embedded seek")

        gate.requestRate(0.5, at: 4)
        gate.requestPlay()
        gate.observe(position: 3.1, rate: 1, isPlaying: true, at: 4.1)
        require(!gate.canSchedule(at: 4.1), "Play must preserve a pending speed change")
        gate.observe(position: 3.2, rate: 0.5, isPlaying: true, at: 4.2)
        require(!gate.canSchedule(at: 4.2), "A speed acknowledgment must wait for movement at that speed")
        gate.observe(position: 3.225, rate: 0.5, isPlaying: true, at: 4.25)
        require(gate.canSchedule(at: 4.25), "Confirmed slower playback must schedule at its actual rate")
        gate.requestRate(0.25, at: 5)
        gate.observe(position: 3.3, rate: 0.5, isPlaying: true, at: 5.1)
        require(!gate.canSchedule(at: 5.1), "Unconfirmed speed change must remain gated")
        gate.observe(position: 4, rate: 0.5, isPlaying: true, at: 6.6)
        require(!gate.canSchedule(at: 6.6), "A timed-out speed request must still prove current movement")
        gate.observe(position: 4.025, rate: 0.5, isPlaying: true, at: 6.65)
        require(gate.canSchedule(at: 6.65), "Declined speed request must recover at the observed actual rate")

        gate.observe(position: 4.025, rate: 0.5, isPlaying: false, at: 6.7)
        require(!gate.canSchedule(at: 6.7), "Buffering stops clicks")
        gate.observe(position: 4.025, rate: 0.5, isPlaying: true, at: 6.75)
        require(!gate.canSchedule(at: 6.75), "A buffering recovery flag must not reuse prior motion")
        gate.observe(position: 4.05, rate: 0.5, isPlaying: true, at: 6.8)
        require(gate.canSchedule(at: 6.8), "Forward media progress must resume after buffering")
        gate.requestSeek(0.1, from: 0.2, at: 7)
        gate.observe(position: 0.2, rate: 1, isPlaying: true, at: 7.01)
        require(!gate.canSchedule(at: 7.01), "A short loop's old endpoint cannot acknowledge its seek")
        gate.observe(position: 0.11, rate: 1, isPlaying: true, at: 7.1)
        require(!gate.canSchedule(at: 7.1), "Backward loop landing must not count as forward playback")
        gate.observe(position: 0.16, rate: 1, isPlaying: true, at: 7.15)
        require(gate.canSchedule(at: 7.15), "Short loops resume after a confirmed seek and forward movement")

        gate.invalidateSource()
        gate.observe(position: 0.2, rate: 1, isPlaying: true, at: 7.2)
        require(!gate.canSchedule(at: 7.2), "A new clock source cannot inherit another source's progress")
        gate.observe(position: 0.25, rate: 1, isPlaying: true, at: 7.25)
        require(gate.canSchedule(at: 7.25), "A new source must establish its own advancing clock")
        gate.requestSeek(10, at: 8)
        gate.invalidateSource()
        gate.observe(position: 0.3, rate: 1, isPlaying: true, at: 8)
        gate.observe(position: 0.35, rate: 1, isPlaying: true, at: 8.05)
        require(!gate.canSchedule(at: 8.05), "Changing clock sources must preserve a pending seek")
        gate.observe(position: 10, rate: 1, isPlaying: true, at: 8.1)
        gate.observe(position: 10.05, rate: 1, isPlaying: true, at: 8.15)
        require(gate.canSchedule(at: 8.15), "A new source can confirm the pending seek and then advance")
        gate.observe(position: 10.1, rate: 1, isPlaying: true, at: 8.14)
        require(!gate.canSchedule(at: 8.14), "Backwards host time must invalidate progress")
        gate.reset()
        require(!gate.canSchedule(at: 9), "Reset must clear progress")
        gate.observe(position: .nan, rate: 1, isPlaying: true, at: 9)
        require(!gate.canSchedule(at: 9), "Invalid media samples must remain gated")
        print("Playback clock checks passed (\(checks)): real forward progress, startup, transport, buffering, source changes and discontinuities.")
    }
}
